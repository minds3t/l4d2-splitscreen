"""Expose retained Xbox controller settings in the current PC options flyout.

The game uses OptionsFlyout.res in both the main menu and pause menu. Keep
the stock PC settings and insert Valve's existing Controller dialog beside
Keyboard/Mouse. Adapt its Xbox pitch range to the PC input convention.
"""
from copy import deepcopy
from pathlib import Path

import kv


OPTIONS_FLYOUT = "resource/ui/l4d360ui/optionsflyout.res"
CONTROLLER_OPTIONS = "resource/ui/l4d360ui/controlleroptions.res"


def _get(children, key):
    return next((value for name, value, _ in children if name.lower() == key.lower()), None)


def _set(children, key, value):
    for index, (name, old, condition) in enumerate(children):
        if name.lower() == key.lower():
            children[index] = (name, value, condition)
            return
    children.append((key, value, None))


def _pc(condition):
    return condition is not None and "WIN32" in condition.upper()


def patch_optionsflyout(text):
    nodes = kv.parse(text)
    roots = [value for _, value, _ in nodes if isinstance(value, list)]
    if len(roots) != 1:
        raise ValueError("OptionsFlyout.res must have exactly one root block")
    controls = roots[0]
    if any(name == "BtnXboxController" for name, _, _ in controls):
        raise ValueError("Xbox controller button is already present")

    keyboard = next((children for _, children, condition in controls
                     if isinstance(children, list) and _pc(condition)
                     and _get(children, "command") == "KeyboardMouse"), None)
    xbox = next((children for _, children, condition in controls
                 if isinstance(children, list) and condition == "$X360"
                 and _get(children, "command") == "Controller"), None)
    background = next((children for name, children, _ in controls
                       if name == "PnlBackground"), None)
    if keyboard is None or xbox is None or background is None:
        raise ValueError("Stock PC keyboard, Xbox controller or background control is missing")

    keyboard_name = _get(keyboard, "fieldName")
    following_name = _get(keyboard, "navDown")
    following_index = next((index for index, (name, _, condition) in enumerate(controls)
                            if name == following_name and _pc(condition)), None)
    if following_index is None:
        raise ValueError("Keyboard/Mouse navigation target is missing")
    following = controls[following_index][1]
    row_height = int(_get(keyboard, "tall"))
    insert_y = int(_get(following, "ypos"))

    # Only move PC-specific rows; the retained Xbox branch stays as Valve ships it.
    for _, children, condition in controls:
        if not isinstance(children, list) or not _pc(condition):
            continue
        ypos = _get(children, "ypos")
        if ypos is not None and int(ypos) >= insert_y:
            _set(children, "ypos", str(int(ypos) + row_height))
    resized = False
    for index, (name, value, condition) in enumerate(background):
        if name.lower() == "tall" and _pc(condition):
            background[index] = (name, str(int(value) + row_height), condition)
            resized = True
    if not resized:
        raise ValueError("PC options background height is missing")

    button = deepcopy(xbox)
    _set(button, "fieldName", "BtnXboxController")
    _set(button, "ypos", str(insert_y))
    _set(button, "navUp", keyboard_name)
    _set(button, "navDown", following_name)
    _set(keyboard, "navDown", "BtnXboxController")
    _set(following, "navUp", "BtnXboxController")
    controls.insert(following_index, ("BtnXboxController", button, "$WIN32"))
    return "// Generated by Splitscreen Support: native Xbox Controller settings added to PC options.\n" + kv.dump(nodes) + "\n"


def patch_controlleroptions(text):
    """Adapt Xbox-only assumptions in the retained Controller dialog for PC.

    Retain the native controls for the dialog's initialization code. That code
    updates their label/flyout but does not override visibility or enabled state.
    Duck Mode's option_duck_method cvar is absent from the PC engine. The native
    Defaults callback executes config.360.cfg, replacing PC input/graphics
    settings with console settings, so that action must also remain hidden.
    PC pitch
    sensitivity must be positive: the Xbox slider otherwise clamps +1 to -0.55
    merely by opening the dialog, reversing the right stick's vertical axis.
    """
    nodes = kv.parse(text)
    roots = [value for _, value, _ in nodes if isinstance(value, list)]
    if len(roots) != 1:
        raise ValueError("ControllerOptions.res must have exactly one root block")
    controls = {name: children for name, children, _ in roots[0]
                if isinstance(children, list)}
    required = ("ControllerOptions", "BtnEditButtons", "DrpLookType", "DrpDuckMode", "BtnDefaults", "SldVertSens")
    if any(name not in controls for name in required):
        raise ValueError("Stock controller settings layout changed")
    duck = controls["DrpDuckMode"]
    button = _get(duck, "BtnDropButton")
    if not isinstance(button, list):
        raise ValueError("Duck Mode dropdown button is missing")
    for panel in (duck, button):
        _set(panel, "visible", "0")
        _set(panel, "enabled", "0")
    defaults = controls["BtnDefaults"]
    _set(defaults, "visible", "0")
    _set(defaults, "enabled", "0")
    _set(defaults, "command", "")
    _set(controls["DrpLookType"], "navDown", "BtnEditButtons")
    _set(controls["BtnEditButtons"], "navUp", "DrpLookType")
    defaults_y = int(_get(defaults, "ypos"))
    duck_y = int(_get(duck, "ypos"))
    if defaults_y <= duck_y:
        raise ValueError("Defaults must follow the Duck Mode row")
    frame = controls["ControllerOptions"]
    row_height = defaults_y - duck_y
    _set(frame, "tall", str(int(_get(frame, "tall")) - 2 * row_height))

    pitch = controls["SldVertSens"]
    if _get(pitch, "conCommand") != "joy_pitchsensitivity":
        raise ValueError("Vertical sensitivity slider no longer controls joy_pitchsensitivity")
    low, high = float(_get(pitch, "minValue")), float(_get(pitch, "maxValue"))
    if not low < high < 0:
        raise ValueError("Stock Xbox pitch sensitivity range changed")
    _set(pitch, "minValue", f"{abs(high):g}")
    _set(pitch, "maxValue", f"{abs(low):g}")
    # Omit the Xbox-only default helper (-1.5). SliderControl then reads the
    # actual PC joy_pitchsensitivity default (+1). Inversion remains controlled
    # solely by the native Look Type setting, joy_inverty, for each player.
    pitch[:] = [(name, value, condition) for name, value, condition in pitch
                if name.lower() not in ("concommanddefault", "inversefill")]
    _set(pitch, "inverseFill", "0")
    return "// Generated by Splitscreen Support: PC pitch slider and supported controller settings.\n" + kv.dump(nodes) + "\n"


def generate(read_stock, out_dir):
    written = []
    for rel, patch in ((OPTIONS_FLYOUT, patch_optionsflyout),
                       (CONTROLLER_OPTIONS, patch_controlleroptions)):
        target = Path(out_dir) / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(patch(read_stock(rel)), encoding="utf-8")
        written.append(rel)
    return written
