"""Extend Valve's offline GameSettings layout to Versus and Scavenge.

The native SoloPlay_<mode> handler accepts these registered modes, but the
shared offline resource only ships the Survival layout for modes without a
difficulty setting. Reuse that layout and the existing mode-specific mission
flyouts; game/session creation and chapter selection remain native.
"""
from copy import deepcopy
from pathlib import Path

import kv


GAME_SETTINGS = "resource/ui/l4d360ui/gamesettings.res"


def _block(nodes, name):
    matches = [value for key, value, _ in nodes if key == name and isinstance(value, list)]
    if len(matches) != 1:
        raise ValueError(f"Expected one stock {name} block, found {len(matches)}")
    return matches[0]


def _set(nodes, name, value):
    matches = [i for i, (key, _, condition) in enumerate(nodes) if key == name and condition is None]
    if len(matches) > 1:
        raise ValueError(f"Multiple unconditional {name} values in stock resource")
    node = (name, value, None)
    if matches:
        nodes[matches[0]] = node
    else:
        nodes.append(node)


def _mode_branch(nodes, mode):
    name = f"?condition?{mode}"
    matches = [value for key, value, _ in nodes if key == name]
    if matches:
        if len(matches) != 1 or not isinstance(matches[0], list):
            raise ValueError(f"Invalid {name} stock branch")
        return matches[0]
    children = []
    nodes.append((name, children, None))
    return children


def patch_gamesettings(text):
    nodes = kv.parse(text)
    roots = [value for _, value, _ in nodes if isinstance(value, list)]
    if len(roots) != 1:
        raise ValueError("GameSettings.res must have exactly one root")
    controls = roots[0]
    if any(key in ("FlmMissionScavenge", "FlmMissionVersus") for key, _, _ in controls):
        raise ValueError("Offline mode flyouts are already present")

    # Survival already defines the native compact no-difficulty layout, down
    # to both platform row sizes and start/back arrow positions.
    def extend_survival_branches(children):
        for _, value, _ in list(children):
            if isinstance(value, list):
                extend_survival_branches(value)
        existing = {key for key, _, _ in children}
        for key, value, condition in list(children):
            if key == "?condition?survival":
                for mode in ("versus", "scavenge"):
                    name = f"?condition?{mode}"
                    if name in existing:
                        raise ValueError(f"Stock already contains {name}; review mode layout")
                    children.append((name, deepcopy(value), condition))

    extend_survival_branches(controls)
    mission_button = _block(_block(controls, "DrpMission"), "BtnDropButton")
    survival_flyout = _block(controls, "FlmMissionSurvival")
    for mode in ("versus", "scavenge"):
        name = "FlmMission" + mode.capitalize()
        _set(_mode_branch(mission_button, mode), "command", name)
        flyout = deepcopy(survival_flyout)
        _set(flyout, "fieldName", name)
        _set(flyout, "ResourceFile", f"resource/UI/L4D360UI/DropDownMission{mode.capitalize()}.res")
        controls.append((name, flyout, None))

    # Navigation must skip the hidden difficulty row as well as its geometry.
    for mode in ("survival", "versus", "scavenge"):
        _set(_mode_branch(_block(controls, "DrpChapter"), mode), "navDown", "DrpCharacter")
        _set(_mode_branch(_block(controls, "DrpCharacter"), mode), "navUp", "DrpChapter")

    return "// Generated by Splitscreen Support: native offline mode layouts and mission flyouts.\n" + kv.dump(nodes) + "\n"


def generate(read_stock, out_dir):
    target = Path(out_dir) / GAME_SETTINGS
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(patch_gamesettings(read_stock(GAME_SETTINGS)), encoding="utf-8")
    return [GAME_SETTINGS]
