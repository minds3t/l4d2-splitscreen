"""Generate the Xbox 360 HUD/UI layouts from the game's own files.

Valve ships one set of .res files for both platforms; the Xbox layout sits
behind [$X360] conditionals that the PC client never selects. This evaluates
the *current* stock PC files as if the game were running on an Xbox 360 and
writes the platform-specialized result, so a Valve update only needs a rebuild.
Language and device conditions remain for the running PC game to evaluate.

    python tools/packaging/xbox_ui.py OUT_DIR      (used by build_packages.py)

Only files whose Xbox evaluation actually differs are written. Schemes whose
[$X360] branch is a console stub (sourcescheme, chatscheme: every font turns
into 7pt Courier) and the Xbox main-menu screens are left alone.
"""
