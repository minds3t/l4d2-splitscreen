# Comparison profiles for diagnostics and tests (English, widescreen, 720p).
X360 = {"X360", "X360WIDE", "X360HIDEF", "ENGLISH"}
WIN32 = {"WIN32", "WIN32WIDE", "WIN32HIDEF", "WINDOWS", "ENGLISH"}
# Force only layout platform flags. Do not bake English, Steam Deck, or a
# desktop font platform into the addon; the live client still selects those.
PLATFORM_SYMBOLS = {
    "X360", "X360WIDE", "X360HIDEF", "X360LODEF",
    "WIN32", "WIN32WIDE", "WIN32HIDEF", "WIN32LODEF", "WINDOWS",
}


def dump(nodes, indent=0):
    """KeyValues text; #base/#include directives must stay unquoted."""
    return kv.dump(nodes, indent) + "\n"


def convert(text):
    """Select Xbox layout branches while retaining non-platform conditions."""
    nodes = kv.parse(text)
    x = kv.specialize(nodes, {name: name in X360 for name in PLATFORM_SYMBOLS})
    w = kv.specialize(nodes, {name: name in WIN32 for name in PLATFORM_SYMBOLS})
    # Keep repeated siblings and their order: dict comparison can miss changes
    # in a repeated font definition or carousel entry with the same name.
    if x == w:
        return None
    return "// Generated by Splitscreen Support: stock Xbox 360 layout; runtime language/device conditions preserved.\n" + dump(x)


def generate(read_stock, out_dir):
    written = []
    for rel in FILES:
        text = convert(read_stock(rel).replace("\r\n", "\n"))
        if text is None:
            continue
        path = os.path.join(out_dir, *rel.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w", encoding="utf-8", newline="\r\n").write(text)
        written.append(rel)
    return written


if __name__ == "__main__":
    import game_files
    for rel in generate(game_files.read_stock, sys.argv[1]):
        print("xbox ui:", rel)
